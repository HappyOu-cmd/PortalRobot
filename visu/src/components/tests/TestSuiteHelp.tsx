export function TestSuiteHelp({ catalog, selectedSuite }: { catalog: Catalog; selectedSuite?: string }) {
  return <Dialog
    title="Что входит в тесты"
    description="Состав наборов, условия запуска и ожидаемый результат."
    className="test-suite-help"
    trigger={<Button variant="ghost" size="icon" icon={helpIcon} className="tw-help-trigger"
      aria-label="Что входит в тесты" title="Что входит в тесты" />}
  >
    <div className="tsh-intro">
      <p>Наборы исполняются через PLC. Тип магазинов выбирается заранее и при запуске теста автоматически не меняется.</p>
      <p><strong>Когда тест пройден:</strong> PLC выполнил ожидаемое действие, достиг заданного результата и сохранил баланс изделий.
        Для сценария с намеренной ошибкой успех — ожидаемый отказ загрузки либо правильная обработка аварии и восстановление.
        Полный цикл требуется только там, где он задан сценарием.</p>
      <p>В результате каждого случая доступны причина, этап и сравнение «Ожидали / Получили».</p>
    </div>
    <div className="tsh-suites">
      {Object.entries(suites).map(([key, suite]) => {
        const entries = catalog[key];
        const details = coverage[key];
        return <details key={key} className="tsh-suite" open={key === selectedSuite}>
          <summary>
            <span className="tsh-suite-heading"><strong>{suite.label}</strong>
              <span className="tsh-count">{key === 'generated' ? '1–1000 комбинаций'
                : entries ? `Сценариев: ${entries.length}` : 'Каталог не загружен'}</span>
            </span>
            <span className="tsh-description">{suite.description}</span>
          </summary>
          <div className="tsh-suite-body">
            {details && <>
              <ul>{details.checks.map(check => <li key={check}>{check}</li>)}</ul>
              <p className="tsh-conditions"><strong>Условия:</strong> {details.conditions}</p>
            </>}
            {key !== 'generated' && (entries?.length ? <details className="tsh-cases">
              <summary>Все сценарии набора · {entries.length}</summary>
              <ol>{entries.map(entry => <li key={entry.index} value={entry.index}>
                <strong>{entry.name}</strong>{entry.description && <p>{entry.description}</p>}
              </li>)}</ol>
            </details> : <p className="tsh-unavailable">Точные названия сценариев появятся после загрузки каталога из gateway.</p>)}
          </div>
        </details>;
      })}
    </div>
    <div className="tsh-saved">
      <h3>Сохранённые сценарии</h3>
      <p>Собственные проверки из вкладки «Сценарии»: начальное состояние и ожидаемый результат задаются в редакторе.
        Для запуска можно выбрать один или несколько сценариев в библиотеке.</p>
      <p>Набор «Основные» уже входит в «Регрессию»; количества этих наборов пересекаются.</p>
    </div>
  </Dialog>;
}
